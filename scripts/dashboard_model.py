"""## 2 — Fungsi revisi yang menjaga struktur kode

Fungsi hanya mengubah blok yang dikenali dan memeriksa sintaks Python sebelum menyimpan.
"""

import ast
import re

def must_find(source: str, marker: str, *, start: int = 0) -> int:
    location = source.find(marker, start)
    if location < 0:
        raise ValueError(f"Struktur kode tidak sesuai / penanda tidak ditemukan: {marker[:110]!r}")
    return location


def revise(source: str) -> str:
    """Revisi hanya isi dashboard; sengaja gagal jika versi file tidak sesuai."""
    if 'def page_overview() -> None:' not in source or 'def page_recommendation() -> None:' not in source:
        raise ValueError("Bukan dashboard_model.py dari proyek Ruang Sales yang diharapkan.")

    # 1. Tampilan perbandingan model pada Ringkasan menjadi lebar penuh,
    #    bukan dua kolom dengan panel ARI di sisi kanan.
    section_start = must_find(source, '    # ---- Perbandingan representasi ----')
    head = '    a, c = st.columns([1.55, 1], gap="medium")\n    with a, st.container(border=True):\n'
    start = must_find(source, head, start=section_start)
    right = must_find(source, '    with c, st.container(border=True):\n', start=start + len(head))
    end = must_find(source, '    a, c = st.columns(2, gap="medium")\n', start=right)
    # Yang dipertahankan hanya isi kolom kiri (hasil evaluasi Silhouette, DBI, CHI, dll).
    body = source[start + len(head):right]
    if 'section("Hasil klasterisasi"' not in body or 'adjusted_rand_score' not in source[right:end]:
        raise ValueError("Blok perbandingan ARI Ringkasan tidak sesuai dengan versi yang diperiksa.")
    source = source[:start] + '    with st.container(border=True):\n' + body + source[end:]

    # 2. Hapus seluruh Insight utama beserta penyusunan kalimat-kalimatnya.
    start = must_find(source, '    # ---- Insight utama (semua angka dihitung langsung dari data & hasil model) ----')
    end = must_find(source, '\n# =======================================================================================\n# 02 · Eksplorasi data', start=start)
    removed = source[start:end]
    if 'section("Insight utama"' not in removed:
        raise ValueError("Kotak Insight utama tidak ditemukan di blok yang akan dihapus.")
    source = source[:start] + source[end:]

    # 3. Hapus heatmap ARI pada tab Rekomendasi Metode, simpan variable keys
    #    karena masih diperlukan tombol navigasi ke halaman Klasterisasi.
    page_start = must_find(source, 'def page_recommendation() -> None:')
    ari_start_marker = '        keys = {rep: k for rep, k in res["best"].items() if k}\n        if len(keys) >= 2:\n'
    start = must_find(source, ari_start_marker, start=page_start)
    end = must_find(source, '        if st.button("Buka model terbaik representasi default di Klasterisasi"', start=start)
    if 'adjusted_rand_score' not in source[start:end] or 'rc_ari' not in source[start:end]:
        raise ValueError("Blok ARI Rekomendasi Metode tidak sesuai.")
    source = source[:start] + '        keys = {rep: k for rep, k in res["best"].items() if k}\n' + source[end:]

    # 4. Hapus kartu ARI pada halaman Metodologi.
    old_metric = '("η² minggu nol", "↓", "Tinggi = klaster hanya memisah produk jarang laku."), ("ARI", "↑", "Kesamaan dua pembagian produk (0–1).")'
    if source.count(old_metric) != 1:
        raise ValueError("Daftar metrik Metodologi berbeda dari versi yang diperiksa.")
    source = source.replace(old_metric, '("η² minggu nol", "↓", "Tinggi = klaster hanya memisah produk jarang laku.")', 1)

    # 5. Impor ARI tak lagi dibutuhkan.
    source = source.replace('from sklearn.metrics import adjusted_rand_score\n', '', 1)

    # Pastikan tidak ada komponen ARI tertinggal dan tidak ada kesalahan sintaks.
    if re.search(r'\bARI\b|adjusted_rand_score|Insight utama', source, flags=re.IGNORECASE):
        raise ValueError("Masih ada referensi ARI/Insight utama dalam dashboard_model.py.")
    ast.parse(source)
    compile(source, 'dashboard_model.py', 'exec')
    return source

"""## 3 — Jalankan revisi dan buat cadangan

Jika file asli sudah pernah direvisi, tidak akan diproses ulang. Perubahan **belum otomatis dikirim ke GitHub**.
"""

hasil_revisi = None
if target is None or not target.is_file():
    print('Belum dapat dijalankan: unggah dashboard_model.py di Langkah 1.')
else:
    original = target.read_text(encoding='utf-8')
    if ('    # ---- Insight utama (semua angka dihitung langsung dari data & hasil model) ----' not in original
            and 'adjusted_rand_score' not in original):
        print('Tidak ada penanda ARI/Insight utama. File mungkin sudah direvisi atau versinya berbeda.')
    else:
        try:
            updated = revise(original)
        except ValueError as exc:
            print('Revisi tidak dilakukan agar file tetap aman:', exc)
        else:
            backup = target.with_suffix(target.suffix + '.bak')
            backup.write_text(original, encoding='utf-8')
            target.write_text(updated, encoding='utf-8')
            hasil_revisi = target
            print('Berhasil memperbarui:', target)
            print('Backup file asli:', backup)
            print('ARI dan Insight utama dihapus; model serta hasil_model/ tidak diubah.')

